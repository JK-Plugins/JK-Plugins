/// XYZ → リニア sRGB
#[rustfmt::skip]
const XYZ_RGB: [[f32; 3]; 3] = [
    [3.2409699419045200, -1.537383177570090, -0.4986107602930030],
    [-0.9692436362808790, 1.875967501507720, 0.0415550574071756],
    [0.0556300796969936, -0.203976958888976, 1.0569715142428700],
];

fn uncompand(x: f32) -> f32 {
    if x < 0.04045 {
        x / 12.92
    } else {
        ((x + 0.055) / 1.055).powf(2.4)
    }
}

fn compand(x: f32) -> f32 {
    if x < 0.0031308 {
        x * 12.92
    } else {
        1.055 * x.powf(1.0 / 2.4) - 0.055
    }
}

/// K/S（吸収と散乱の比）
fn ks(r: f32) -> f32 {
    (1.0 - r) * (1.0 - r) / (2.0 * r)
}

/// K/S から反射率に戻す（1 + x - sqrt(x² + 2x) と同じ。桁落ちしない形）
pub fn km(x: f32) -> f32 {
    1.0 / (1.0 + x + (x * x + 2.0 * x).sqrt())
}

/// sRGB の値（0..1）を反射率にする
fn reflectance(rgb: [f32; 3]) -> [f32; SIZE] {
    let [r, g, b] = rgb.map(|v| uncompand(v.clamp(0.0, 1.0)));
    let w = r.min(g).min(b);
    let (r, g, b) = (r - w, g - w, b - w);
    let c = g.min(b);
    let m = r.min(b);
    let y = r.min(g);
    let rr = (r - b).max(0.0).min((r - g).max(0.0));
    let gg = (g - b).max(0.0).min((g - r).max(0.0));
    let bb = (b - g).max(0.0).min((b - r).max(0.0));
    let k = [w, c, m, y, rr, gg, bb];
    std::array::from_fn(|i| {
        let mut v = 0.0;
        for j in 0..7 {
            v += k[j] * BASE[i][j];
        }
        v.max(EPSILON)
    })
}

fn to_xyz(r: &[f32; SIZE]) -> [f32; 3] {
    let mut xyz = [0.0f32; 3];
    for i in 0..SIZE {
        for c in 0..3 {
            xyz[c] += r[i] * CMF[i][c];
        }
    }
    xyz
}

/// XYZ → sRGB の値（0..1 に収める）
pub fn xyz_to_srgb(xyz: [f32; 3]) -> [f32; 3] {
    std::array::from_fn(|c| {
        let l = XYZ_RGB[c][0] * xyz[0] + XYZ_RGB[c][1] * xyz[1] + XYZ_RGB[c][2] * xyz[2];
        compand(l).clamp(0.0, 1.0)
    })
}

/// 混ぜる1色（前もって求めておく）
#[derive(Clone, Copy, Debug)]
pub struct Pigment {
    pub ks: [f32; SIZE],
    /// 輝度（濃度の重み）
    pub lum: f32,
    /// 元の色と、この色だけを混ぜたとき（反射率を通して戻したとき）の差。
    /// 混ぜた結果に量で重み付けて足し、グラデーションの端が元の色にぴったり戻るようにする
    pub resid: [f32; 3],
}

impl Pigment {
    pub fn new(rgb: [f32; 3]) -> Self {
        let r = reflectance(rgb);
        let lum = to_xyz(&r)[1].max(f32::EPSILON);
        let k = r.map(ks);
        // mix と同じ道筋（K/S → 反射率 → 色）で戻したもの
        let back = xyz_to_srgb(to_xyz(&k.map(km)));
        Self {
            ks: k,
            lum,
            resid: std::array::from_fn(|c| rgb[c] - back[c]),
        }
    }
}

/// 色と量（0..1、合計 1）を混ぜた sRGB の値
pub fn mix(items: impl Iterator<Item = (Pigment, f32)> + Clone) -> [f32; 3] {
    let mut total = 0.0f32;
    let mut resid = [0.0f32; 3];
    for (p, f) in items.clone() {
        total += f * f * p.lum;
        for c in 0..3 {
            resid[c] += p.resid[c] * f;
        }
    }
    if total <= 0.0 {
        return resid;
    }
    let mut xyz = [0.0f32; 3];
    for i in 0..SIZE {
        let mut k = 0.0f32;
        for (p, f) in items.clone() {
            k += p.ks[i] * (f * f * p.lum);
        }
        let r = km(k / total);
        for c in 0..3 {
            xyz[c] += r * CMF[i][c];
        }
    }
    let rgb = xyz_to_srgb(xyz);
    std::array::from_fn(|c| rgb[c] + resid[c])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn yellow_and_blue_make_green() {
        let y = Pigment::new([0.988, 0.827, 0.0]);
        let b = Pigment::new([0.0, 0.129, 0.522]);
        let m = mix([(y, 0.5), (b, 0.5)].into_iter());
        assert!(m[1] > m[0] && m[1] > m[2], "{m:?}");
    }

    #[test]
    fn matches_spectral_js_example() {
        // Spectral.js の README の例：#002185 と #FCD200 を半分ずつ → #3D933E
        let a = [0x00, 0x21, 0x85].map(|v| v as f32 / 255.0);
        let b = [0xFC, 0xD2, 0x00].map(|v| v as f32 / 255.0);
        let (pa, pb) = (Pigment::new(a), Pigment::new(b));
        // 端を合わせる補正（resid）を除いたもの
        let m = mix([(pa, 0.5), (pb, 0.5)].into_iter());
        let raw: [f32; 3] = std::array::from_fn(|c| m[c] - 0.5 * (pa.resid[c] + pb.resid[c]));
        let want = [0x3D, 0x93, 0x3E].map(|v| v as f32 / 255.0);
        for c in 0..3 {
            assert!((raw[c] - want[c]).abs() < 2.0 / 255.0, "{raw:?} vs {want:?}");
        }
    }

    #[test]
    fn ends_are_exact() {
        for rgb in [[1.0, 0.0, 0.0], [0.2, 0.6, 0.9], [0.0, 0.0, 0.0], [1.0, 1.0, 1.0]] {
            let p = Pigment::new(rgb);
            let q = Pigment::new([0.5, 0.5, 0.1]);
            let m = mix([(p, 1.0), (q, 0.0)].into_iter());
            for c in 0..3 {
                assert!((m[c] - rgb[c]).abs() < 1e-5, "{rgb:?} -> {m:?}");
            }
        }
    }
}
